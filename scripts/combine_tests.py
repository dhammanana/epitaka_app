"""Write test/_combined/shard_<n>.dart: every test file, split over a few files.

`flutter test` compiles one test file at a time, so a full run of one file per
process spends most of its time waiting for the compiler. A shard imports a
share of the test files and runs each one's main() inside a group named by its
path, so it compiles once and failing names still say which file they are from.

    uv run scripts/combine_tests.py   # then: flutter test test/_combined/shard_*.dart

Passing the folder instead runs every *_test.dart in test/, one file per
process, because flutter test keeps only *_test.dart files from a folder.

The shards are named without `_test` so a plain `flutter test` or a one-file
run never picks them up a second time. `just test` runs this before each run,
so a new test file joins the next run with no edit here.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEST_DIR = ROOT / "test"
OUT_DIR = TEST_DIR / "_combined"
# Hangs forever (see AGENTS.md, "Running the tests").
EXCLUDED = {"test/mdx_repro_test.dart"}

TEST_CALL = re.compile(r"\b(?:test|testWidgets)\(")
TEST_ON = re.compile(r"^@TestOn\((['\"])(.+?)\1\)", re.MULTILINE)
ASYNC_MAIN = re.compile(r"\bmain\s*\(\s*\)\s*async\b")
# The @TestOn selectors this script can turn into a skip, mapped to
# Platform.operatingSystem. Any other selector stops the script.
TEST_ON_OS = {"linux": "linux", "windows": "windows", "mac-os": "macos"}
# File-level test annotations a shard would silently drop: a skipped file
# would start running, a longer timeout would vanish.
UNHANDLED_ANNOTATION = re.compile(r"^@(?:Skip|Timeout|Tags|OnPlatform|Retry)\b", re.MULTILINE)


def test_files() -> list[str]:
    return sorted(
        p.relative_to(ROOT).as_posix()
        for p in TEST_DIR.rglob("*_test.dart")
        if OUT_DIR not in p.parents and p.relative_to(ROOT).as_posix() not in EXCLUDED
    )


def split(files: dict[str, int], shards: int) -> list[list[str]]:
    # Largest first onto the lightest shard. A file with no test calls still
    # costs a compile and a start-up, so it weighs at least 1.
    buckets: list[list[str]] = [[] for _ in range(shards)]
    loads = [0] * shards
    for path in sorted(files, key=lambda p: (-max(files[p], 1), p)):
        i = loads.index(min(loads))
        buckets[i].append(path)
        loads[i] += max(files[path], 1)
    return [sorted(b) for b in buckets]


def test_on(source: str) -> str | None:
    m = TEST_ON.search(source)
    return m.group(2) if m else None


def shard_source(paths: list[str], sources: dict[str, str]) -> str:
    platform_bound = any(test_on(sources[p]) for p in paths)
    lines = [
        "// Generated by scripts/combine_tests.py. Do not edit.",
        *(["import 'dart:io' show Platform;", ""] if platform_bound else []),
        "import 'package:flutter_test/flutter_test.dart';",
        "",
    ]
    for i, path in enumerate(paths):
        lines.append(f"import '../{Path(path).relative_to('test').as_posix()}' as t{i};")
    lines += ["", "void main() {"]
    for i, path in enumerate(paths):
        # A file-level @TestOn would be lost in the shard, and flutter_test's
        # group() takes no testOn, so it becomes a skip on the group.
        selector = test_on(sources[path])
        skip = ""
        if selector:
            os = TEST_ON_OS[selector]
            skip = f", skip: Platform.operatingSystem == '{os}' ? false : \"@TestOn('{selector}')\""
        lines.append(f"  group('{path}', t{i}.main{skip});")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Split the test files over a few shard files.")
    parser.add_argument("--shards", type=int, default=8)
    args = parser.parse_args()

    paths = test_files()
    sources = {p: (ROOT / p).read_text(encoding="utf-8") for p in paths}
    async_mains = [p for p in paths if ASYNC_MAIN.search(sources[p])]
    if async_mains:
        # test_api throws "Groups may not be async." on these.
        print("main() must not be async in: " + ", ".join(async_mains), file=sys.stderr)
        return 1
    unknown = [p for p in paths if (s := test_on(sources[p])) and s not in TEST_ON_OS]
    if unknown:
        print("@TestOn selector not handled in: " + ", ".join(unknown), file=sys.stderr)
        return 1
    annotated = [p for p in paths if UNHANDLED_ANNOTATION.search(sources[p])]
    if annotated:
        print("File-level test annotation not handled in: " + ", ".join(annotated), file=sys.stderr)
        return 1

    counts = {p: len(TEST_CALL.findall(sources[p])) for p in paths}
    OUT_DIR.mkdir(exist_ok=True)
    for old in OUT_DIR.glob("shard_*.dart"):
        old.unlink()
    for n, shard in enumerate(split(counts, args.shards), start=1):
        (OUT_DIR / f"shard_{n}.dart").write_text(shard_source(shard, sources), encoding="utf-8")
        print(f"shard_{n}.dart: {len(shard)} files, {sum(counts[p] for p in shard)} tests")
    return 0


if __name__ == "__main__":
    sys.exit(main())
